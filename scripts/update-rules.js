import { mkdir, writeFile } from "node:fs/promises";

// Pin updates for review; never download rules while the extension is running.
const commit = "c080ff46cb381b092c09d46977e4f2e76b38ae5f";
const base = `https://raw.githubusercontent.com/ClearURLs/Rules/${commit}/`;
async function download(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`Download failed: ${response.status} ${url}`);
  return response.text();
}
const data = JSON.parse(await download(`${base}data.min.json`));
const rules = Object.values(data.providers)
  .filter((provider) => provider.rules?.length && !provider.completeProvider)
  .map((provider) => [provider.urlPattern, provider.rules, provider.exceptions || []]);
// Store only query-removal rules; preserve patterns and exceptions verbatim.
await mkdir("rules", { recursive: true });
await writeFile(
  "rules/clearurls.js",
  `// Generated by scripts/update-rules.js. See NOTICE.txt.\nexport default ${JSON.stringify(rules)};\n`,
);
await writeFile("rules/LICENSE-LGPL-3.0.txt", await download(`${base}LICENSE`));
await writeFile(
  "rules/LICENSE-GPL-3.0.txt",
  await download(
    "https://raw.githubusercontent.com/spdx/license-list-data/main/text/GPL-3.0-only.txt",
  ),
);
await writeFile(
  "rules/NOTICE.txt",
  `Includes query-removal rules derived from ClearURLs/Rules.\nCopyright ClearURLs contributors. Licensed under LGPL-3.0.\nSource: https://github.com/ClearURLs/Rules/tree/${commit}\nModified: projected to URL patterns, parameter rules, and exceptions only.\nRegenerate: node scripts/update-rules.js\nReadable rules are distributed in clearurls.js; accompanying licenses apply to them.\n`,
);
console.log(`Vendored ${rules.length} query-rule providers from ${commit}`);
